import { readFile, writeFile } from "node:fs/promises";
import { BOT_AVATAR_COLORS, BOT_AVATAR_COLOR_NAMES } from "@openteam/contracts/bot-avatar";
import colors from "../../../packages/design-tokens/src/message-colors.json";
const path = new URL("../Sources/Core/MessageFeatures.swift", import.meta.url);
const marker = "// BEGIN GENERATED MESSAGE COLORS";
const original = await readFile(path, "utf8");
const rows = BOT_AVATAR_COLORS.map((avatar, i) => {
  const name = BOT_AVATAR_COLOR_NAMES[i]!;
  const value = colors.find((color) => color.name === name);
  return `    (0x${avatar.slice(1)}, ${value ? `("${value.light.slice(1)}", "${value.dark.slice(1)}")` : "nil"}),`;
}).join("\n");
const generated = `${marker}
// Generated by scripts/export-message-colors.ts from design-tokens/message-colors.json.
public enum MessageBubblePalette {
  private static let entries: [(UInt32, (light: String, dark: String)?)] = [
${rows}
  ]
  public static func colors(for color: String?) -> (light: String, dark: String)? {
    guard let color, color.hasPrefix("#"), color.count == 7,
      let rgb = UInt32(color.dropFirst(), radix: 16) else { return nil }
    func distance(_ candidate: UInt32) -> Int {
      [16, 8, 0].reduce(0) { sum, shift in
        let delta = Int((candidate >> shift) & 255) - Int((rgb >> shift) & 255)
        return sum + delta * delta
      }
    }
    return entries.min { distance($0.0) < distance($1.0) }?.1
  }
}
// END GENERATED MESSAGE COLORS
`;
const next = original.split(marker)[0]!.trimEnd() + "\n\n" + generated;
if (process.argv.includes("--check")) {
  if (next !== original)
    throw Error("Message colors are stale; run bun apps/ios/scripts/export-message-colors.ts");
} else await writeFile(path, next);
