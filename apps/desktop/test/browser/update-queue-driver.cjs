const { app, BrowserWindow } = require("electron");
const fs = require("node:fs");
const path = require("node:path");
app.setPath("userData", path.join(__dirname, "profile"));
const delay = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 1100, height: 800, webPreferences: { backgroundThrottling: false } });
  const js = (code) => win.webContents.executeJavaScript(code);
  let passed = 0;
  const assert = async (code, message) => { if (!await js(code)) throw new Error(message + ": " + await js("document.body.innerText")); passed++; };
  const wait = async (code, message) => { for (let i = 0; i < 200; i++) { if (await js(code)) { passed++; return; } await delay(50); } throw new Error(message + ": " + await js("document.body.innerText")); };
  const load = async (query = "") => { await win.loadURL(process.argv[2] + query); await wait("window.updateDemo?.ready && document.querySelector('[data-update-state]')?.dataset.updateState !== 'loading'", "fixture ready"); };
  const click = async (label) => { await js(`(()=>{const button=[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===${JSON.stringify(label)});if(!button||button.disabled)throw new Error('Missing or disabled button: '+${JSON.stringify(label)});button.click()})()`); await delay(100); };
  const shot = async (name) => fs.writeFileSync(path.join(process.argv[3], name + ".png"), (await win.webContents.capturePage()).toPNG());

  await load("?manual");
  await assert("document.body.innerText.includes('Update to 0.0.19') && document.body.innerText.includes('Update desktop')", "matching old versions offer independent updates");
  await click("Update"); await click("Click Again to Confirm");
  await wait("updateDemo.posts.length===1", "server update submitted");
  await assert("updateDemo.posts[0]==='0.0.19' && updateDemo.downloads===0 && updateDemo.installs===0", "server-only action does not touch desktop");

  await load("?scenario=desktop&fast");
  await click("Update desktop");
  await wait("updateDemo.state().desktop.status==='downloaded'", "desktop-only download");
  await assert("updateDemo.posts.length===0 && updateDemo.installs===0", "desktop-only action does not touch server or auto restart");
  await click("Not now");

  await load("?manual");
  await click("Update both…");
  await wait("document.querySelector('[role=alertdialog]')?.textContent.includes('No bots are working')", "confirmation checks bots");
  await assert("updateDemo.posts.length===0 && updateDemo.downloads===0", "review is read-only");
  await shot("01-review");
  await click("Cancel");
  await assert("updateDemo.posts.length===0", "cancel leaves everything unchanged");
  await click("Update both…");
  await wait("document.querySelector('[role=alertdialog]')?.textContent.includes('No bots are working')", "reopened confirmation");
  await click("Update both");
  await wait("document.querySelector('[data-update-queue]')?.textContent.includes('Queued') && updateDemo.posts.length===1", "server starts and desktop queues");
  await assert("updateDemo.downloads===0", "desktop waits for server");
  await js("updateDemo.offline=true");
  await delay(1700);
  await assert("updateDemo.downloads===0 && document.querySelector('[data-update-queue]').dataset.updateQueue==='running'", "server restart does not advance the queue");
  await js("updateDemo.offline=false;updateDemo.events.push('server-verified');updateDemo.server({status:'updated',phase:'complete',currentVersion:'0.0.19'})");
  await wait("updateDemo.downloads===1", "desktop starts after verified server reconnect");
  await assert("JSON.stringify(updateDemo.events)==='[\"server-start\",\"server-verified\",\"desktop-download\"]'", "server and desktop execute in order");
  await js("updateDemo.emit({status:'downloaded',progress:100})");
  await wait("document.querySelector('[data-update-queue]')?.dataset.updateQueue==='complete'", "queue finishes at ready-to-restart");
  await assert("updateDemo.installs===0", "queue never auto restarts");
  await click("Not now");
  await shot("02-ready-to-restart");

  await load("?manual");
  await click("Update both…");
  await wait("document.querySelector('[role=alertdialog]')?.textContent.includes('No bots are working')", "failure review ready");
  await click("Update both");
  await wait("updateDemo.posts.length===1", "failure server started");
  await js("updateDemo.server({status:'error',message:'Server signature verification failed'})");
  await wait("document.querySelector('[data-update-queue]')?.dataset.updateQueue==='error'", "queue pauses on server error");
  await assert("updateDemo.downloads===0 && document.body.innerText.includes('Server signature verification failed')", "failure blocks desktop and reports cause");
  await shot("03-failure");
  await js("updateDemo.server({status:'updated',phase:'complete',currentVersion:'0.0.19'})");
  await delay(150);
  await click("Retry queue");
  await wait("updateDemo.downloads===1", "retry continues to desktop");
  await assert("updateDemo.posts.length===1", "retry does not reinstall the updated server");
  await js("updateDemo.emit({status:'downloaded'})");
  await wait("document.querySelector('[data-update-queue]')?.dataset.updateQueue==='complete'", "retry completes");
  await click("Not now");

  await load("?manual");
  await js("updateDemo.busy=true");
  await click("Update both…");
  await wait("document.querySelector('[role=alertdialog]')?.textContent.includes('1 bot is still working')", "confirmation reports busy bots");
  await assert("[...document.querySelectorAll('button')].find(b=>b.textContent.trim()==='Update both').disabled && updateDemo.posts.length===0", "busy bots block update confirmation");
  await click("Cancel");
  await js("updateDemo.busy=false;document.documentElement.dataset.theme='dark'");
  await shot("04-dark");
  win.setSize(390, 800);
  await delay(200);
  await assert("document.documentElement.scrollWidth<=innerWidth", "narrow view fits");
  await shot("05-narrow");
  fs.writeFileSync(path.join(process.argv[3], "results.json"), JSON.stringify({ passed, scenarios: ["independent server update", "independent desktop update", "read-only review and cancel", "server before desktop", "reconnect gate", "explicit restart", "server failure blocks desktop", "retry preserves completed work", "busy bots", "dark and narrow layouts"] }, null, 2));
  console.log(`${passed} update queue UI checks passed`);
  app.quit();
}).catch((error) => { console.error(error); app.exit(1); });
